"""Paper F sources table (Task 12): papers/F/sources.md.

    python -I pipeline/hmis/run_f.py sources      # writes papers/F/sources.md

sources_md_f(out) writes one row per data/raw/hmis entry of data/MANIFEST.csv (path, URL, retrieval date (UTC), SHA-256,
licence), one row per external input of the perinatal model table (the ONI and RONI index files, the IMD gridded rainfall
and Tmax files, the GADM boundaries), the repository reference files behind the link units, and the programme-event
sources of the indicators Paper F uses, with the verbatim GODL-India attribution. It reuses Paper E's
pipeline/hmis/sources_md.py (hmis_rows, GODL_ATTRIBUTION, PORTAL_ONLY, EXTERNAL) unchanged. Portal-only FY2020-21 files
are cited to the portal, which states no explicit licence; FY2020-21 enters Paper F only as a sensitivity analysis. No
data value is written, and no local path is ever printed.

Hand-off: papers/F/sources.md (tracked; regenerated in full on every run, rows in MANIFEST order).
"""
import csv
from pathlib import Path

from pipeline.hmis import sources_md as sm
from pipeline.paths import MANIFEST_PATH, ROOT

OUT_PATH_F = ROOT / "papers" / "F" / "sources.md"
EVENTS_PATH = sm.EVENTS_PATH
# External inputs of the perinatal model table (a subset of sm.EXTERNAL; Paper F uses no population, DMI or Nino-3.4 input).
F_EXTERNAL_PATHS = ("data/raw/enso/oni.ascii.txt", "data/raw/enso/RONI.ascii.txt", "data/raw/imd/rain_",
                    "data/raw/imd/tmax_", "data/external/gadm41_IND.gpkg")
F_EVENT_INDICATORS = ("hmis_format2017", "demonet", "pmsma", "laqshya")
# Repository reference files behind the link units and the item crosswalk: (path, what).
F_REFERENCE = [
    ("pipeline/reference/hmis_link_units.csv",
     "GADM link units: the connected components of HMIS district-FYs and GADM 4.1 districts (names only)"),
    ("pipeline/reference/hmis_perinatal_crosswalk.csv", "Perinatal item crosswalk (HMIS item codes to analysis variables)"),
    ("pipeline/reference/hmis_perinatal_reviewed.csv", "Author-reviewed gate dispositions"),
    ("pipeline/reference/hmis_district_review.csv", "Hand-resolved district names (source and disposition)"),
    ("pipeline/reference/nfhs_district_crosswalk.csv",
     "District-name crosswalk of an earlier paper of this programme, used for names only; no survey data is used or redistributed"),
]


def _external(manifest: Path) -> list[dict]:
    rows = sm._manifest(manifest)
    lic = {k: (what, lc) for k, what, lc in sm.EXTERNAL}
    out = []
    for key in F_EXTERNAL_PATHS:
        what, lc = lic[key]
        hit = [r for r in rows if (r["path"].startswith(key) if key.endswith(("/", "_")) else r["path"] == key)]
        if not hit:
            raise ValueError(f"external input {key} has no MANIFEST row")
        out += [{"path": r["path"], "what": what, "url": sm.public_url(r["path"], r["url"]),
                 "retrieved": r["retrieved_utc"][:10], "sha256": r["sha256"], "licence": lc} for r in hit]
    return out


def _events(events: Path) -> list[dict]:
    with open(events, newline="", encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh) if r["indicator"] in F_EVENT_INDICATORS]
    return [{"event": r["event"], "indicator": r["indicator"], "source": r["source_url"], "accessed": r["accessed"],
             "status": "PROVISIONAL (pending the author's confirmation)" if "PROVISIONAL" in r["note"] else "confirmed"}
            for r in rows]


def sources_md_f(out: Path = OUT_PATH_F, manifest: Path = MANIFEST_PATH, events: Path = EVENTS_PATH,
                 root: Path = ROOT) -> Path:
    hm = sm.hmis_rows(manifest)
    ex = _external(manifest)
    ev = _events(events)
    n_godl = sum(r["licence"] == sm.GODL_SHORT for r in hm)
    n_portal = sum(r["licence"] == sm.PORTAL_ONLY for r in hm)
    cell = sm._cell
    lines = [
        "# Paper F: data sources",
        "",
        "Generated by `pipeline/hmis/perinatal_sources.py` (`python -I pipeline/hmis/run_f.py sources`) from `data/MANIFEST.csv`, "
        "`pipeline/reference/hmis_programme_events.csv` and the repository files named below. Do not edit by hand.",
        "",
        "## Attribution (HMIS)",
        "",
        sm.GODL_ATTRIBUTION,
        "",
        f"HMIS files for FY2012-13 to FY2019-20 ({n_godl} files) are used under this attribution. The FY2020-21 files "
        f"({n_portal} files) were downloaded from the hmis.mohfw.gov.in portal only; they are cited to the portal, "
        "which states no explicit licence, and FY2020-21 enters the analysis only as a sensitivity analysis. Raw HMIS "
        "files are not redistributed.",
        "",
        f"## HMIS portal files ({len(hm)} rows of `data/MANIFEST.csv` under `data/raw/hmis/`)",
        "",
        "| Path | URL | Retrieved (UTC) | SHA-256 | Licence |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| `{r['path']}` | {cell(r['url'])} | {r['retrieved']} | `{r['sha256']}` | "
              f"{cell(r['licence'] + (' (file deleted)' if r['deleted'] else ''))} |" for r in hm]
    lines += [
        "",
        f"## External inputs ({len(ex)} files)",
        "",
        "Inputs of `data/derived/hmis/perinatal_model.csv.gz` other than HMIS: the ONI and RONI ENSO indices, IMD gridded "
        "rainfall and maximum temperature (SPI-3, Tmax anomaly, heatwave days) and the GADM boundaries (link units).",
        "",
        "| Path | Input | URL | Retrieved (UTC) | SHA-256 | Licence |",
        "|---|---|---|---|---|---|",
    ]
    lines += [f"| `{r['path']}` | {cell(r['what'])} | {cell(r['url'])} | {r['retrieved']} | `{r['sha256']}` | "
              f"{cell(r['licence'])} |" for r in ex]
    lines += [
        "",
        f"## Repository reference files ({len(F_REFERENCE)} files)",
        "",
        "SHA-256 values are of the repository file after CRLF -> LF.",
        "",
        "| Path | Content | SHA-256 (LF) |",
        "|---|---|---|",
    ]
    lines += [f"| `{p}` | {cell(what)} | `{sm._sha256_lf(root / p)}` |" for p, what in F_REFERENCE]
    lines += [
        "",
        f"## Programme-event sources ({len(ev)} rows of `pipeline/reference/hmis_programme_events.csv`)",
        "",
        "Cited sources for the programme-indicator months used by Paper F (`hmis_format2017`, `demonet`, `pmsma`, "
        "`laqshya`); fetched pages, where kept, are listed above with their SHA-256 under `data/raw/hmis/programme_events/`. "
        "Programme-event months stay provisional until the author confirms them.",
        "",
        "| Event | Indicator | Source | Accessed | Status |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {cell(r['event'])} | `{r['indicator']}` | {cell(r['source'])} | {r['accessed']} | {r['status']} |" for r in ev]
    text = "\n".join(lines) + "\n"
    bad = [ln for ln in text.splitlines() if sm.LOCAL_PATH_RE.search(ln)]
    if bad:
        raise ValueError(f"sources.md would print a local path: {bad[0][:120]}")
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    return out


def sources_step() -> int:
    out = sources_md_f()
    print(f"wrote {out}")
    return 0
